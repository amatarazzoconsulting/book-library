// NEBULA JIT pipeline (book section 7). Source text or a hand built AST goes
// through an optimizer, a bytecode compiler and a stack VM, and comes out as a
// callable closure. Three tiers are available: direct AST walk, plain bytecode
// and optimized bytecode.
#pragma once

#include <cstddef>
#include <cstdint>
#include <functional>
#include <memory>
#include <string>
#include <unordered_map>
#include <vector>

#include "box_value.hpp"

namespace nebula {

enum class BinOp { ADD, SUB, MUL, DIV, MOD, LT, GT, LE, GE, EQ, NE, BAND, BOR, BXOR, SHL, SHR };
enum class UnOp { NEG, NOT };
enum class Tier { AST = 0, BYTECODE = 1, OPTIMIZED = 2 };
enum class Language { AUTO, NEBULA, BASIC, PYTHON };

class Expr;
class Stmt;
class Block;
using ExprPtr = std::shared_ptr<Expr>;
using StmtPtr = std::shared_ptr<Stmt>;
using BlockPtr = std::shared_ptr<Block>;

class Block {
public:
    std::vector<StmtPtr> stmts;
    static BlockPtr make();
};

class Expr {
public:
    enum class Kind { CONST, VAR, BINOP, UNARYOP, CALL };

    Kind kind;
    Box value;                 // CONST
    std::string name;          // VAR, CALL
    BinOp binop = BinOp::ADD;  // BINOP
    UnOp unop = UnOp::NEG;     // UNARYOP
    ExprPtr lhs, rhs;
    std::vector<ExprPtr> args;

    static ExprPtr Const(const Box& v);
    static ExprPtr Var(const std::string& n);
    static ExprPtr BinOp_(BinOp op, ExprPtr l, ExprPtr r);
    static ExprPtr UnaryOp_(UnOp op, ExprPtr e);
    static ExprPtr Call_(const std::string& n, const std::vector<ExprPtr>& a);

    // Structural helpers used by the optimizer.
    bool isConst() const { return kind == Kind::CONST; }
    ExprPtr clone() const;
    std::string toString() const;
    std::size_t nodeCount() const;
};

class Stmt {
public:
    enum class Kind { EXPR, ASSIGN, IF, WHILE, RETURN, BLOCK };

    Kind kind;
    std::string var;          // ASSIGN
    ExprPtr expr;             // EXPR, ASSIGN, RETURN, IF/WHILE condition
    BlockPtr body;            // IF then, WHILE body, BLOCK
    BlockPtr elseBody;        // IF else

    static StmtPtr Expr_(ExprPtr e);
    static StmtPtr Assign(const std::string& v, ExprPtr e);
    static StmtPtr If(ExprPtr cond, BlockPtr thenB, BlockPtr elseB = nullptr);
    static StmtPtr While(ExprPtr cond, BlockPtr body);
    static StmtPtr Return(ExprPtr v = nullptr);
    static StmtPtr Block_(BlockPtr b);

    StmtPtr clone() const;
    std::string toString() const;
};

struct OptimizeOptions {
    bool constant_folding = true;
    bool constant_propagation = true;
    bool dead_code_elimination = true;
    bool strength_reduction = true;
    bool algebraic_simplification = true;
    std::size_t max_passes = 4;  // fixed point iterations
};

struct OptimizeReport {
    std::size_t folds = 0;
    std::size_t propagations = 0;
    std::size_t dead_stmts = 0;
    std::size_t strength_reductions = 0;
    std::size_t algebraic = 0;
    std::size_t passes_run = 0;
};

struct JITOptions {
    Tier tier = Tier::OPTIMIZED;
    OptimizeOptions optimize;
    bool trace = false;            // print each pipeline stage
    bool check_arity = true;
    std::size_t stack_limit = 4096;
};

struct JITStats {
    std::size_t ast_nodes = 0;
    std::size_t bytecode_ops = 0;
    std::size_t vm_steps = 0;
    std::size_t closures_built = 0;
    std::size_t calls = 0;
    OptimizeReport opt;
};

struct VMResult {
    Box value;
    std::size_t steps = 0;
};

class JITCompiler {
public:
    explicit JITCompiler(JITOptions opt = JITOptions());

    void addStatement(StmtPtr stmt);
    void addExpression(ExprPtr expr);  // becomes the program result
    void parseSource(const std::string& source, Language lang = Language::AUTO);
    void setLanguage(Language lang) { language_ = lang; }

    ExprPtr optimize(ExprPtr expr);
    void setOptimizationLevel(const OptimizeOptions& o) { opt_.optimize = o; }
    void setTier(Tier t) { opt_.tier = t; }

    void setGlobal(const std::string& name, const Box& value);
    Box getGlobal(const std::string& name) const;
    void registerFunction(const std::string& name,
                          std::function<Box(std::vector<Box>&)> fn);

    // Build the executable closure (runs optimizer + codegen).
    class Closure;
    std::shared_ptr<Closure> compile();
    Box execute();
    Box call(const std::string& fn, const std::vector<Box>& args);

    const JITOptions& options() const { return opt_; }
    const JITStats& stats() const { return stats_; }
    void resetStats() { stats_ = JITStats(); }

    // Exposed for teaching: the generated bytecode as text.
    std::vector<std::string> disassemble() const;

private:
    JITOptions opt_;
    JITStats stats_;
    Language language_ = Language::AUTO;
    BlockPtr program_;
    std::unordered_map<std::string, Box> globals_;
    std::unordered_map<std::string, std::function<Box(std::vector<Box>&)>> builtins_;
    std::shared_ptr<Closure> closure_;
};

// A compiled program plus its compiled user functions.
class JITCompiler::Closure {
public:
    Closure(std::string name, Tier tier);
    Box call(const std::vector<Box>& args);
    const std::string& name() const { return name_; }
    Tier tier() const { return tier_; }
    std::size_t bytecodeSize() const { return code_.size(); }
    std::vector<std::string> disassemble() const;
    void setCode(std::vector<std::int32_t> code, std::vector<Box> consts,
                 std::vector<std::string> names, std::vector<std::int32_t> lines);
    std::vector<std::int32_t>& code() { return code_; }
    const std::vector<Box>& consts() const { return consts_; }
    std::vector<std::string>& names() { return names_; }
    void bindGlobals(std::unordered_map<std::string, Box>* g) { globals_ = g; }
    void bindBuiltins(std::unordered_map<std::string,
                      std::function<Box(std::vector<Box>&)>>* b) { builtins_ = b; }
    VMResult run(std::size_t stack_limit);
    std::size_t steps() const { return steps_; }

private:
    std::string name_;
    Tier tier_;
    std::vector<std::int32_t> code_;
    std::vector<Box> consts_;
    std::vector<std::string> names_;
    std::vector<std::int32_t> lines_;
    std::unordered_map<std::string, Box>* globals_ = nullptr;
    std::unordered_map<std::string, std::function<Box(std::vector<Box>&)>>* builtins_ = nullptr;
    std::size_t steps_ = 0;
};

// Free helpers used by demo/teaching/tests.
ExprPtr parseExpression(const std::string& source);
std::string describeTier(Tier t);

}  // namespace nebula
